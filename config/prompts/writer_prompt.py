# 岗位分类的通用指导框架，{position_instructions} 会被下面函数生成的文本替换
POSITION_INSTRUCTION_TEMPLATE = """## 岗位分类指导（{category}）

### 核心关键词（必须自然融入经历描述）
{keywords}

### 优先量化指标类型（重点使用这些类型的量化数据）
{metrics}

### 推荐强动词（替换弱动词如"负责""参与"）
{verbs}

### 行业写作指导
{guidance}

"""


def build_position_prompt(position_category: str) -> str:
    """根据岗位分类，从 position_prompts.py 加载对应的差异化提示词。

    返回的文本会注入到 WRITER_TEMPLATE 的 {position_instructions} 位置。
    如果岗位分类为空或"其他"，返回空字符串（使用通用模板）。
    """
    if not position_category or position_category == "其他":
        return ""
    from config.prompts.position_prompts import get_position_config
    config = get_position_config(position_category)
    return POSITION_INSTRUCTION_TEMPLATE.format(
        category=position_category,
        keywords="、".join(config["keywords"]),
        metrics="、".join(config["metrics"]),
        verbs="、".join(config["verbs"]),
        guidance=config["system_prompt"].strip(),
    )
